#!/usr/bin/env node
// Generates verify.js: tests/verify.ts and everything it imports in one plain-JavaScript file, so `node verify.js` runs the
// whole suite on Node 22 with nothing installed and no TypeScript flags. Built with Bun's bundler (auditor tooling only;
// the output needs nothing but Node). verify.js reads data/, evidence/ and outputs/ from the folder it sits in.
import { spawnSync } from 'node:child_process';
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
// the Bun version that builds the bundle is written into its header (and RELEASE-MANIFEST.json toolchain.bun), so a
// byte difference after a rebuild on another Bun reads as a toolchain difference, not as a changed verifier
const bunVersion = (spawnSync('bun', ['--version'], { encoding: 'utf8' }).stdout || '').trim() || 'unknown';
const r = spawnSync('bun', ['build', 'tests/verify.ts', '--target=node', '--format=esm', '--outfile=verify.js.tmp'], { cwd: ROOT, encoding: 'utf8' });
if (r.status !== 0) { console.error(r.stdout, r.stderr); process.exit(1); }
const body = readFileSync(join(ROOT, 'verify.js.tmp'), 'utf8');
// The sha256 of every source the bundle is built from (tests/verify.ts and src/*.ts); verify.js refuses to run
// when the sources beside it differ (a stale bundle), so verify.js and tests/verify.ts cannot drift apart undetected.
const srcs = ['tests/verify.ts', ...readdirSync(join(ROOT, 'src')).filter((f) => f.endsWith('.ts')).sort().map((f) => `src/${f}`)];
const hashes = Object.fromEntries(srcs.map((f) => [f, createHash('sha256').update(readFileSync(join(ROOT, f))).digest('hex')]));
const header = `/**\n * STANDALONE VERIFIER — generated by scripts/build-standalone.mjs from tests/verify.ts, do not edit.\n *\n *     node verify.js\n *\n * Node 22, nothing to install. Built with Bun ${bunVersion} (bun build --target=node --format=esm).\n * Source sha256 of tests/verify.ts: ${hashes['tests/verify.ts']}\n * Sources sha256: ${JSON.stringify(hashes)}\n */\n`;
writeFileSync(join(ROOT, 'verify.js'), header + body);
spawnSync('rm', ['-f', join(ROOT, 'verify.js.tmp')]);
console.log(`wrote verify.js (${(header + body).length} chars, Bun ${bunVersion})`);
